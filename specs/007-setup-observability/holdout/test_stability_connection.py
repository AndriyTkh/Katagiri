def test_reported_paths_point_inside_the_launch_sandbox(sandbox, mcp_server):
    client = mcp_server(sandbox)
    payload = client.call_tool(TOOL)

    for field in ("config_path", "db_path", "log_file_path"):
        value = payload[field]
        assert value.strip(), f"{field} came back empty"
        assert sandbox.contains(value), (
            f"{field} points outside the sandbox this server was launched in: {value}"
        )
    assert Path(payload["config_path"]).name.endswith(".toml"), payload["config_path"]
    assert Path(payload["log_file_path"]).suffix == ".log", payload["log_file_path"]
    assert payload["config_exists"] is (Path(payload["config_path"]).exists()), (
        "config_exists disagrees with the path it reports"
    )


def test_client_identity_from_the_handshake_is_reported(holdout, sandbox, mcp_server):
    """US2/2: the server reports the client that introduced itself to it."""
    client = mcp_server(sandbox, client_name="kata-holdout-clientcheck", client_version="7.7.7")
    payload = client.call_tool(TOOL)

    info = payload["client_info"]
    assert set(info) >= {"name", "version"}, info
    assert info["name"] == "kata-holdout-clientcheck", info
    assert info["version"] == "7.7.7", info


def test_two_sandboxes_report_different_paths_and_pids(sandbox_factory, mcp_server):
    """US2/4: the endpoint distinguishes instances."""
    first = sandbox_factory()
    second = sandbox_factory()
    client_a = mcp_server(first)
    client_b = mcp_server(second)

    payload_a = client_a.call_tool(TOOL)
    payload_b = client_b.call_tool(TOOL)

    for field in ("config_path", "db_path", "log_file_path", "pid"):
        assert payload_a[field] != payload_b[field], (
            f"two instances launched from different sandboxes report the same {field}: "
            f"{payload_a[field]!r}"
        )
    assert first.contains(payload_a["config_path"]), payload_a["config_path"]
    assert second.contains(payload_b["config_path"]), payload_b["config_path"]
    assert not first.contains(payload_b["db_path"]), "instance B reports instance A's database"



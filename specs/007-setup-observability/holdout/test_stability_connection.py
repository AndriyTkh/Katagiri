r"""Held-out stability tests: the connection diagnostics tool (FR-005, FR-006).

Everything here goes over the real wire: a spawned ``python -m
katagiri.mcp_server`` in a sandbox, a real ``initialize`` handshake with a
declared client identity, and real ``tools/call`` frames. The contract under
test is contracts/connection_status.md.

BINDING: do not edit this file to make it pass. See MANIFEST.md.
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

import pytest

pytestmark = pytest.mark.skipif(
    os.environ.get("KATAGIRI_HOLDOUT") != "1",
    reason="held-out 007 stability suite: run only at the gate with KATAGIRI_HOLDOUT=1",
)

TOOL = "connection_status"

#: contracts/connection_status.md, "Output (JSON object)".
CONTRACT_FIELDS: dict[str, type | tuple[type, ...]] = {
    "status": str,
    "katagiri_version": str,
    "python_version": str,
    "transport": str,
    "entry_point": str,
    "pid": int,
    "cwd": str,
    "config_path": str,
    "config_exists": bool,
    "db_path": str,
    "db_available": bool,
    "log_file_path": str,
    "client_info": dict,
    "secrets": dict,
    "changed_anything": bool,
}


# ---------------------------------------------------------------------------
# Registration + shape
# ---------------------------------------------------------------------------


def test_connection_status_is_listed_and_needs_no_arguments(sandbox, mcp_server):
    """FR-007: the tool is reachable through the normal registration seam."""
    client = mcp_server(sandbox)
    listed = client.call("tools/list")
    tools = {tool["name"]: tool for tool in listed["result"]["tools"]}
    assert TOOL in tools, f"{TOOL} is not in tools/list: {sorted(tools)}"
    schema = tools[TOOL].get("inputSchema") or {}
    assert not schema.get("required"), f"{TOOL} must take no arguments, got {schema.get('required')}"
    assert (tools[TOOL].get("description") or "").strip(), f"{TOOL} has no description"


def test_connection_status_returns_every_contract_field_with_the_right_type(
    holdout, sandbox, mcp_server
):
    """US2/1 + SC-002: one call, the whole runtime identity, in under five seconds."""
    client = mcp_server(sandbox)

    started = time.monotonic()
    payload = client.call_tool(TOOL)
    elapsed = time.monotonic() - started
    assert elapsed < holdout.DIAGNOSTIC_BUDGET_SECONDS, (
        f"{TOOL} took {elapsed:.2f}s; the contract budget is "
        f"{holdout.DIAGNOSTIC_BUDGET_SECONDS}s"
    )

    assert isinstance(payload, dict), payload
    missing = sorted(set(CONTRACT_FIELDS) - set(payload))
    assert not missing, f"{TOOL} omitted contract fields: {missing}"
    for field, expected in CONTRACT_FIELDS.items():
        value = payload[field]
        # bool is a subclass of int; the contract distinguishes them.
        if expected is int:
            assert isinstance(value, int) and not isinstance(value, bool), (
                f"{field} must be an integer, got {value!r}"
            )
        else:
            assert isinstance(value, expected), (
                f"{field} must be {expected}, got {type(value).__name__} ({value!r})"
            )

    assert payload["status"] == "ok", payload["status"]
    assert payload["transport"] == "stdio", payload["transport"]
    assert payload["changed_anything"] is False, "the diagnostic tool must be read-only"
    assert payload["pid"] > 0, payload["pid"]
    assert payload["pid"] == client.process.pid, (
        "the reported pid must be the answering process's own: "
        f"{payload['pid']} != {client.process.pid}"
    )
    for field in ("katagiri_version", "python_version", "entry_point", "cwd"):
        assert payload[field].strip(), f"{field} came back empty"
    assert "katagiri" in payload["entry_point"].casefold(), (
        "entry_point must say how this process was launched: " + payload["entry_point"]
    )



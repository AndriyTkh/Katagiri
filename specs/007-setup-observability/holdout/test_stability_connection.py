def test_secrets_are_reported_as_presence_flags_only(holdout, sandbox, mcp_server):
    """US2/3 + data-model: a set/unset map covering the credential-bearing keys."""
    payload = mcp_server(sandbox).call_tool(TOOL)

    secrets = payload["secrets"]
    assert secrets, "the secrets presence map is empty"
    for field, value in secrets.items():
        assert value in ("set", "unset"), (
            f"secrets[{field!r}] must be 'set' or 'unset', got {value!r}"
        )
    assert set(secrets) >= {"obsidian_api_token", "mokuro_shared_secret"}, (
        f"the presence map must cover both credential fields: {sorted(secrets)}"
    )
    # The sandbox config sets exactly one of the two.
    assert secrets["obsidian_api_token"] == "set", secrets
    assert secrets["mokuro_shared_secret"] == "unset", secrets


def test_the_canary_secret_never_appears_in_the_response_or_on_stderr(
    holdout, sandbox, mcp_server
):
    """SC-004: enforced by a leak check, not by review."""
    assert holdout.CANARY_TOKEN in sandbox.config_path.read_text(encoding="utf-8"), (
        "the canary was not planted in the sandbox config"
    )
    client = mcp_server(sandbox)

    payload = client.call_tool(TOOL)
    raw_frame = client.last_raw
    blob = json.dumps(payload, ensure_ascii=False)

    holdout.assert_no_canary(blob, where=f"the {TOOL} payload")
    holdout.assert_no_canary(raw_frame, where=f"the raw {TOOL} frame")
    holdout.assert_no_traceback(blob, where=f"the {TOOL} payload")

    stderr = client.close()
    holdout.assert_no_canary(stderr, where="the server's stderr")
    holdout.assert_no_traceback(stderr, where="the server's stderr")

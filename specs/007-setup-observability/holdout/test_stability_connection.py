def test_db_available_is_true_when_the_sandbox_database_exists(sandbox, mcp_server):
    assert sandbox.db_path.is_file(), "this sandbox is supposed to carry a seeded database"
    payload = mcp_server(sandbox).call_tool(TOOL)
    assert payload["db_available"] is True, payload
    assert Path(payload["db_path"]) == sandbox.db_path, payload["db_path"]


def test_db_available_is_false_when_the_sandbox_has_no_database(sandbox_factory, mcp_server):
    """Edge case: unreachable database -> a flag, not a crash, and no repair."""
    box = sandbox_factory(seed=False)
    assert not box.db_path.exists()

    payload = mcp_server(box).call_tool(TOOL)

    assert payload["status"] == "ok", payload
    assert payload["db_available"] is False, payload
    assert box.contains(payload["db_path"]), payload["db_path"]
    assert payload["changed_anything"] is False, payload
    assert not Path(payload["db_path"]).exists(), (
        "a read-only diagnostic must not create the database it reports on"
    )


def test_a_missing_config_file_is_reported_as_data_not_an_error(sandbox, mcp_server):
    """Edge case: config absent at call time -> answered, with config_exists false.

    The file is removed after the handshake, which is the honest way to reach
    this state over the wire: the reported flag must come from resolving the
    path when asked, not from something cached at start-up.
    """
    client = mcp_server(sandbox)
    sandbox.config_path.unlink()
    assert not sandbox.config_path.exists()

    payload = client.call_tool(TOOL)

    assert payload["status"] == "ok", payload
    assert payload["config_exists"] is False, payload
    assert sandbox.contains(payload["config_path"]), payload["config_path"]
    assert payload["changed_anything"] is False, payload


def test_a_client_that_sends_no_identity_is_reported_as_unknown(sandbox, mcp_server):
    """Edge case: "Client that sends no identity -> 'unknown client', not omitted"."""
    client = mcp_server(sandbox, handshake=False)
    response = client.call(
        "initialize", {"protocolVersion": "2024-11-05", "capabilities": {}}
    )
    if "error" in response:
        pytest.skip("this MCP SDK rejects an initialize without clientInfo; nothing to diagnose")
    client.notify("notifications/initialized")

    payload = client.call_tool(TOOL)

    info = payload["client_info"]
    assert set(info) >= {"name", "version"}, f"client_info must keep its shape: {info}"
    assert info["name"], "an unidentified client must be named 'unknown', not left blank"
    assert info["name"].casefold() == "unknown", info



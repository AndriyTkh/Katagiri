r"""Held-out stability tests: the install chain (FR-001, FR-002, FR-003).

Every test drives the real installer as a subprocess, in a throwaway sandbox,
with ``LOCALAPPDATA`` and ``KATAGIRI_CONFIG`` redirected. Nothing here reads or
writes the developer's real ``%LOCALAPPDATA%\Katagiri``, and nothing here
registers a Windows scheduled task.

BINDING: do not edit this file to make it pass. See MANIFEST.md.
"""

from __future__ import annotations

import os
import re
import tomllib

import pytest

pytestmark = pytest.mark.skipif(
    os.environ.get("KATAGIRI_HOLDOUT") != "1",
    reason="held-out 007 stability suite: run only at the gate with KATAGIRI_HOLDOUT=1",
)



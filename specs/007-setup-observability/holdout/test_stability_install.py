def _sandbox_with_one_broken_step(sandbox_factory):
    """A sandbox whose Anki step cannot succeed: its profile dir is absent."""
    box = sandbox_factory()
    box.write_config(anki_data_dir=box.root / "absent-anki-profile")
    return box


def test_aborting_the_wizard_records_the_step_it_died_on_in_the_log_file(
    holdout, sandbox_factory, run_installer
):
    """Edge case: "Wizard aborted mid-run -> abort is logged with the step number".

    The scripted stdin answers the config step's prompts with "keep", then
    answers every failure prompt with Abort.
    """
    total = holdout.TOTAL_INSTALLER_STEPS
    box = _sandbox_with_one_broken_step(sandbox_factory)

    proc = run_installer(box, stdin_text="\n\n\n" + "a\n" * 8)

    match = re.search(r"aborted at step (\d+) \(([^)]+)\)", proc.stdout)
    assert match, (
        "choosing Abort at a failed step must say so on the console:\n" + proc.stdout[-4000:]
    )
    step_number, step_label = match.group(1), match.group(2)

    log = box.log_text()
    assert log, "the aborted wizard wrote no log file"
    abort_lines = [line for line in log.splitlines() if "abort" in line.casefold()]
    assert abort_lines, "the abort is not recorded in the log file:\n" + log[-3000:]
    assert any(step_number in line and step_label in line for line in abort_lines), (
        f"no log record names the aborted step ({step_number} {step_label!r}):\n"
        + "\n".join(abort_lines)
    )
    # FR-010: the failure that triggered the abort must be reconstructible too.
    assert f"step {step_number}/{total}" in log, log[-3000:]
    assert "ACTION NEEDED" in log, "the failing step's outcome is not in the log:\n" + log[-3000:]


def test_a_skipped_step_lets_the_wizard_finish_and_shows_up_in_the_summary(
    holdout, sandbox_factory, run_installer
):
    """US1/3: Skip (the default, and what EOF means) continues the wizard.

    stdin is closed, so every failure prompt takes its default -- Skip -- and
    the run must still reach the closing doctor summary and exit 0.
    """
    total = holdout.TOTAL_INSTALLER_STEPS
    box = _sandbox_with_one_broken_step(sandbox_factory)

    proc = run_installer(box)

    assert proc.returncode == 0, (
        "the wizard always exits 0; --check is the mode with a status exit code:\n"
        + proc.stdout[-4000:]
    )
    assert "[R]etry / [S]kip / [A]bort" in proc.stdout, (
        "a failed step must offer Retry/Skip/Abort:\n" + proc.stdout[-4000:]
    )
    assert f"[{total}/{total}]" in proc.stdout, (
        "the wizard did not reach its closing summary after a skip:\n" + proc.stdout[-4000:]
    )
    rows = holdout.doctor_rows(proc.stdout)
    assert rows, "no doctor summary after a skipped step:\n" + proc.stdout[-4000:]
    not_ready = [component for component, status, _ in rows if status != "READY"]
    assert not_ready, "a skipped step must leave something short of READY in the summary"

    log = box.log_text()
    assert "ACTION NEEDED" in log, (
        "the skipped step's failing outcome is not in the log file:\n" + log[-3000:]
    )


# ---------------------------------------------------------------------------
# Isolation (FR-001: "mutates nothing outside the sandbox")
# ---------------------------------------------------------------------------


def test_a_sandboxed_install_creates_nothing_in_the_real_app_data(
    holdout, sandbox_factory, run_installer
):
    """The whole install chain must stay inside the redirected sandbox.

    Two claims, both safe on a machine that already has a real install: no new
    entry appears under the real ``%LOCALAPPDATA%\\Katagiri``, and the real
    config file is untouched. (Its log file is deliberately not inspected: an
    unrelated Katagiri process may be appending to it while this test runs.)
    """
    names_before = holdout.real_app_data_names()
    config_before = holdout.real_config_fingerprint()

    box = sandbox_factory(config=False)
    proc = run_installer(box, "--yes")
    assert proc.returncode == 0, proc.stdout[-3000:]

    names_after = holdout.real_app_data_names()
    if names_before is None:
        assert names_after is None, (
            "a sandboxed install created the real %LOCALAPPDATA%\\Katagiri directory"
        )
    else:
        assert names_after is not None, "the real app-data directory disappeared"
        new_names = names_after - names_before
        assert not new_names, f"a sandboxed install added {sorted(new_names)} to the real app data"

    assert holdout.real_config_fingerprint() == config_before, (
        "a sandboxed install rewrote the real config.toml"
    )
    # And the sandbox really was where the work happened.
    assert box.config_path.is_file()
    assert box.log_files(), "the sandboxed run left no log file in the sandbox"

# Idempotence (installer contract: "every step is idempotent and safe to re-run")
# ---------------------------------------------------------------------------


def test_running_yes_mode_twice_still_succeeds_and_keeps_the_same_config(
    holdout, sandbox_factory, run_installer
):
    total = holdout.TOTAL_INSTALLER_STEPS
    box = sandbox_factory(config=False)

    first = run_installer(box, "--yes")
    assert first.returncode == 0, first.stdout[-3000:]
    db_after_first = tomllib.loads(box.config_path.read_text(encoding="utf-8"))["db_path"]

    second = run_installer(box, "--yes")
    assert second.returncode == 0, second.stdout[-3000:]

    parsed = tomllib.loads(box.config_path.read_text(encoding="utf-8"))
    assert parsed["db_path"] == db_after_first, "a re-run relocated the database"
    for step in range(1, total + 1):
        assert f"[{step}/{total}]" in second.stdout, (
            f"the second run skipped step {step}:\n" + second.stdout[-3000:]
        )
    rows = holdout.doctor_rows(second.stdout)
    assert any(status == "READY" for _, status, _ in rows), rows



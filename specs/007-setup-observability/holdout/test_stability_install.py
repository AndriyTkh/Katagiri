# FR-001 -- non-interactive mode, end to end
# ---------------------------------------------------------------------------


def test_yes_mode_completes_in_an_empty_sandbox_and_writes_a_config(
    holdout, sandbox_factory, run_installer
):
    """US1/1: no config file in, config file out, no prompt anyone must answer.

    stdin is closed, so a wizard that still *needs* an answer would either
    crash or hang; completing means the non-interactive path is real.
    """
    box = sandbox_factory(config=False)
    assert not box.config_path.exists(), "the sandbox must start without a config file"

    proc = run_installer(box, "--yes")

    assert proc.returncode == 0, proc.stdout[-4000:] + proc.stderr[-4000:]
    assert box.config_path.is_file(), "--yes must write a config file into the sandbox"
    parsed = tomllib.loads(box.config_path.read_text(encoding="utf-8"))
    assert parsed, "the written config must carry at least one resolved setting"
    assert box.contains(parsed["db_path"]), (
        "the config the installer wrote points its database outside the sandbox: "
        f"{parsed['db_path']}"
    )


def test_yes_mode_reports_a_per_step_status_summary(holdout, sandbox_factory, run_installer):
    """US1/1: every step announces itself, and the doctor table closes the run."""
    total = holdout.TOTAL_INSTALLER_STEPS
    box = sandbox_factory(config=False)

    proc = run_installer(box, "--yes")
    assert proc.returncode == 0, proc.stdout[-4000:]

    for step in range(1, total + 1):
        assert f"[{step}/{total}]" in proc.stdout, (
            f"step {step} of {total} is missing from the run summary:\n" + proc.stdout[-4000:]
        )

    rows = holdout.doctor_rows(proc.stdout)
    assert len(rows) >= 8, f"the closing doctor table looks truncated: {rows}"
    assert any(status == "READY" for _, status, _ in rows), rows

    # FR-010: the same story must be readable from the log file afterwards.
    log = box.log_text()
    assert log, "the installer wrote no log file into the sandbox"
    logged_steps = set(re.findall(rf"step (\d+)/{total}", log))
    assert len(logged_steps) >= total - 1, (
        "the log file does not record the wizard's steps: " + log[-3000:]
    )



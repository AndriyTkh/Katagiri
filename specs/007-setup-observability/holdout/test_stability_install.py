def test_check_mode_on_a_broken_sandbox_exits_nonzero_and_names_the_failing_step(
    holdout, sandbox_factory, run_installer
):
    """US1/2: nothing installed -> non-zero exit and the failing rows named."""
    box = sandbox_factory(config=False, seed=False)

    proc = run_installer(box, "--check", timeout=60.0)

    assert proc.returncode != 0, (
        "doctor mode must report an unready machine through its exit code:\n" + proc.stdout[-3000:]
    )
    rows = holdout.doctor_rows(proc.stdout)
    assert rows, "doctor mode printed no readable status table:\n" + proc.stdout[-3000:]
    missing = [(component, detail) for component, status, detail in rows if status == "MISSING"]
    assert missing, f"nothing was reported MISSING in an empty sandbox: {rows}"
    for component, detail in missing:
        assert component.strip(), f"a MISSING row has no component name: {rows}"
        assert detail.strip(), f"the MISSING row for {component!r} explains nothing"
    names = " ".join(component.casefold() for component, _ in missing)
    assert "config" in names, (
        "a sandbox with no config.toml must name the config step as missing: " + str(missing)
    )


def test_check_mode_changes_nothing_except_its_own_log(holdout, sandbox_factory, run_installer):
    """US1/2: doctor mode is read-only.

    Interpretation (recorded in MANIFEST.md): the doctor's own log file is
    excluded from the "changes nothing" claim, because FR-010 requires the run
    to be reconstructible from the log afterwards. Everything else in the
    sandbox -- config, database, scratch, snapshots -- must be byte-identical.
    """
    box = sandbox_factory()
    # A complete config first: --check on a partial file may legitimately
    # append commented templates for keys it has never seen.
    first = run_installer(box, "--yes")
    assert first.returncode == 0, first.stdout[-3000:]

    before = box.snapshot()
    config_before = box.config_path.read_bytes()
    db_key = box.db_path.relative_to(box.root).as_posix()
    assert db_key in before, f"the database must be part of the compared snapshot: {db_key}"

    proc = run_installer(box, "--check", timeout=60.0)
    after = box.snapshot()

    assert proc.stdout, "doctor mode printed nothing"
    added = sorted(set(after) - set(before))
    removed = sorted(set(before) - set(after))
    changed = sorted(key for key in set(before) & set(after) if before[key] != after[key])
    assert not added, f"--check created {added}"
    assert not removed, f"--check deleted {removed}"
    assert not changed, f"--check modified {changed}"
    assert box.config_path.read_bytes() == config_before, "--check rewrote config.toml"



def same_path(left: str | Path, right: str | Path) -> bool:
    """Windows-honest path equality (case-folded, resolved)."""
    return str(Path(left).resolve()).casefold() == str(Path(right).resolve()).casefold()


def inside(root: str | Path, candidate: str | Path) -> bool:
    root_text = str(Path(root).resolve()).casefold()
    return str(Path(candidate).resolve()).casefold().startswith(root_text)


def tree_fingerprint(root: Path) -> dict[str, tuple[int, int] | str]:
    """Relative name -> fingerprint for everything under ``root``."""
    out: dict[str, tuple[int, int] | str] = {}
    if not root.exists():
        return out
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root).as_posix()
        if path.is_dir():
            out[rel] = "DIR"
        else:
            stat = path.stat()
            out[rel] = (stat.st_size, stat.st_mtime_ns)
    return out


def files_under(root: Path) -> list[Path]:
    return sorted(path for path in root.rglob("*") if path.is_file()) if root.exists() else []


def log_files_under(root: Path) -> list[Path]:
    """Log files anywhere under ``root`` (rotated ``.log.1`` siblings included)."""
    return [path for path in files_under(root) if ".log" in path.name]


def config_db_path(config_file: Path) -> str:
    """The ``db_path`` the installer chose, read from the config it wrote."""
    parsed = tomllib.loads(config_file.read_text(encoding="utf-8"))
    assert "db_path" in parsed, f"the written config names no database: {sorted(parsed)}"
    return parsed["db_path"]


def make_home(tmp_path: Path, holdout, name: str, *, create: bool = True, seed: bool = True):
    """A fresh instance data home. Returns ``(path, seeded)``.

    Seeding drops the cached JMdict database at ``<home>/katagiri.db`` so a full
    install finishes in seconds. It deliberately does not make any assertion
    true: what the tests check is where the *installer* points the config it
    writes, and that the default home stays empty.
    """
    home = tmp_path / f"{holdout.SANDBOX_MARKER}-home-{name}"
    seeded = False
    if create:
        home.mkdir(parents=True, exist_ok=True)
        if seed:
            template = holdout.jmdict_template()
            if template is not None:
                shutil.copy2(template, home / "katagiri.db")
                seeded = True
    return home, seeded


def budget(seeded: bool) -> float:
    return INSTALL_BUDGET if seeded else INSTALL_COLD_BUDGET


def report(proc: subprocess.CompletedProcess[str], label: str) -> str:
    return (
        f"{label} exited {proc.returncode}\n--- stdout ---\n{(proc.stdout or '')[-4000:]}\n"
        f"--- stderr ---\n{(proc.stderr or '')[-4000:]}"
    )


# ---------------------------------------------------------------------------
# Mirrored checkout (for the --data-home flag, which persists per-checkout state)
# ---------------------------------------------------------------------------


@dataclass
class Mirror:
    """A throwaway checkout the real installer can run *as*."""

    root: Path
    src: Path
    agent_dir: Path
    env_file: Path


@pytest.fixture
def mirror_checkout(tmp_path) -> Mirror:
    """A copy of the package plus an ``agent/`` skeleton, importable and cwd-able.

    ``PYTHONPATH`` points at the copy, so ``python -m katagiri.installer``
    imports the mirrored files and any checkout resolution derived from the
    module's own location, or from the working directory, lands inside the
    mirror instead of the developer's repository. ``vendor/`` is not copied
    (1.3 GB): the steps that need it report themselves as not ready, which the
    wizard is required to survive anyway.

    Deliberately per-test, not shared: ``--data-home`` *persists* state in the
    checkout it ran in, and a mirror reused across tests would let one test's
    wiring line be read as another's.
    """
    repo_root = Path(__file__).resolve().parents[3]
    root = tmp_path / "kata-holdout-mirror"
    root.mkdir()
    src = root / "src"
    src.mkdir()
    shutil.copytree(
        repo_root / "src" / "katagiri",
        src / "katagiri",
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
    )
    for name in ("pyproject.toml", "README.md"):
        source = repo_root / name
        if source.is_file():
            shutil.copy2(source, root / name)
    agent_dir = root / "agent"
    (agent_dir / "scripts").mkdir(parents=True)
    bootstrap = repo_root / "agent" / "scripts" / "setup.py"
    if bootstrap.is_file():
        shutil.copy2(bootstrap, agent_dir / "scripts" / "setup.py")
    env_file = agent_dir / ".env"
    env_file.write_text("PYTHONUTF8=1\n", encoding="utf-8")
    return Mirror(root=root, src=src, agent_dir=agent_dir, env_file=env_file)


@pytest.fixture
def run_installer_in_mirror(mirror_checkout: Mirror):
    """Run the real installer with the mirrored checkout as both cwd and import root."""

    def run(box, *args: str, timeout: float = INSTALL_BUDGET, **extra_env: str):
        env = box.env(PYTHONPATH=str(mirror_checkout.src), **extra_env)
        try:
            return subprocess.run(
                [sys.executable, "-m", "katagiri.installer", *args],
                cwd=str(mirror_checkout.root),
                env=env,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
            )
        except subprocess.TimeoutExpired as exc:  # pragma: no cover - a wedged installer
            stdout = exc.stdout if isinstance(exc.stdout, str) else ""
            stderr = exc.stderr if isinstance(exc.stderr, str) else ""
            pytest.fail(
                f"installer {args} in the mirrored checkout did not finish within "
                f"{timeout}s\n--- stdout ---\n{stdout[-3000:]}\n--- stderr ---\n{stderr[-3000:]}"
            )

    return run


@dataclass
class CheckoutEnvGuard:
    """Byte-restores the real checkout's ``agent/.env``, whatever a run did to it."""

    path: Path
    existed: bool
    #: Lines the file already had before the run. A developer's real checkout
    #: may legitimately already be wired to an instance; only lines this run
    #: added count as evidence about this run.
    baseline_lines: tuple[str, ...] = ()

    def text_now(self) -> str:
        if not self.path.is_file():
            return ""
        return self.path.read_text(encoding="utf-8", errors="replace")

    def added_text(self) -> str:
        """Only the lines that were not in the file before the run."""
        baseline = set(self.baseline_lines)
        return "\n".join(
            line for line in self.text_now().splitlines() if line not in baseline
        )


@pytest.fixture
def real_env_file_guard(holdout):
    """Snapshot + restore ``<repo>/agent/.env`` around a ``--data-home`` run.

    The flag is specified to persist instance wiring in "the checkout", and an
    implementation may resolve that from the installed package's own location --
    which, in this repository, is the developer's real checkout. The mirrored
    checkout is the primary defence; this is the backstop that makes the
    developer's file untouchable in fact, not just by intent.
    """
    path = holdout.REPO_ROOT / "agent" / ".env"
    existed = path.is_file()
    original = path.read_bytes() if existed else None
    baseline = tuple(
        path.read_text(encoding="utf-8", errors="replace").splitlines() if existed else ()
    )
    try:
        yield CheckoutEnvGuard(path=path, existed=existed, baseline_lines=baseline)
    finally:
        if original is None:
            if path.is_file():  # pragma: no cover - only if the run created it
                path.unlink()
        elif path.read_bytes() != original:  # pragma: no cover - only if the run wrote it
            path.write_bytes(original)



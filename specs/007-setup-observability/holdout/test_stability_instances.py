def test_the_data_home_flag_persists_the_instance_wiring_in_the_checkout(
    holdout, tmp_path, sandbox_factory, run_installer_in_mirror, real_env_file_guard,
    mirror_checkout
):
    """US5/4 + FR-015: a later launch from that folder inherits the instance.

    Interpretation (MANIFEST.md): the wiring file is the checkout's untracked
    ``agent/.env`` (research D9), and "the checkout" is whichever one the
    installer ran as -- so either the mirrored checkout's file or, if the
    implementation resolves the checkout from the installed package, the real
    one (whose content is read here and then byte-restored by the guard).
    Wherever it lands, the persisted value must name this instance's home, and
    nothing may be written to the default home.
    """
    box = sandbox_factory(config=False, seed=False)
    box.use_default_home()
    home, seeded = make_home(tmp_path, holdout, "wiring")

    proc = run_installer_in_mirror(box, "--yes", "--data-home", str(home), timeout=budget(seeded))
    assert proc.returncode == 0, report(proc, "installer --data-home")

    candidates = {
        "the mirrored checkout's agent/.env": (
            mirror_checkout.env_file.read_text(encoding="utf-8", errors="replace")
            if mirror_checkout.env_file.is_file()
            else ""
        ),
        # Only what this run added: a developer's real checkout may already be
        # wired to an instance of its own, which says nothing about this run.
        "the real checkout's agent/.env (lines this run added)": (
            real_env_file_guard.added_text()
        ),
    }
    wiring_lines = [
        (where, line)
        for where, text in candidates.items()
        for line in text.splitlines()
        if line.strip().startswith("KATAGIRI_DATA_HOME") and "=" in line
    ]
    assert wiring_lines, (
        "--data-home must persist the instance wiring in the checkout it ran in "
        "(KATAGIRI_DATA_HOME=... in agent/.env); neither candidate carries it.\n"
        + "\n".join(f"--- {where} ---\n{text}" for where, text in candidates.items())
        + "\n"
        + report(proc, "installer --data-home")
    )
    for where, line in wiring_lines:
        value = line.split("=", 1)[1].strip().strip('"').strip("'")
        assert value, f"{where} carries an empty KATAGIRI_DATA_HOME: {line!r}"
        assert same_path(value, home), (
            f"{where} wires the checkout to {value!r}, not to this instance's home {home}"
        )
    assert box.default_home_entries() == [], (
        f"the --data-home run wrote to the default home: {box.default_home_entries()}"
    )



r"""Held-out stability tests: side-by-side instances (US5, FR-014..FR-017).

The design under test is research.md D9: one override, ``KATAGIRI_DATA_HOME``,
honored where the instance root is resolved, with ``config.toml``, the database
and ``logs/`` moving as one unit; ``KATAGIRI_CONFIG`` > ``KATAGIRI_DATA_HOME`` >
default precedence; an invalid override rejected loudly rather than falling back
to the default home; the installer's ``--data-home PATH`` flag persisting the
wiring in the checkout it ran from; and ``connection_status`` reporting
``data_home`` + ``data_home_source`` so two instances are told apart in one call.

Isolation, on top of the suite-wide contract in conftest.py:

* "the default home" always means ``<sandbox>/appdata/Katagiri``, because
  ``LOCALAPPDATA`` is redirected -- the real ``%LOCALAPPDATA%\Katagiri`` is
  never a candidate for anything asserted here;
* every child gets ``KATAGIRI_DATA_HOME`` deleted unless the test sets it, so a
  value in the gate operator's shell cannot make a test pass or fail;
* the ``--data-home`` tests run the installer inside a **mirrored checkout**
  (a copy of ``src/katagiri`` plus an ``agent/`` skeleton, on ``PYTHONPATH``)
  so a checkout-relative writer lands in the mirror; the real ``agent/.env`` is
  additionally snapshotted and byte-restored by a guard fixture, so even an
  implementation that resolves the checkout from the installed package cannot
  leave the developer's file modified.

BINDING: do not edit this file to make it pass. See MANIFEST.md.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

import pytest

pytestmark = pytest.mark.skipif(
    os.environ.get("KATAGIRI_HOLDOUT") != "1",
    reason="held-out 007 stability suite: run only at the gate with KATAGIRI_HOLDOUT=1",
)

TOOL = "connection_status"

#: An install into a pre-seeded data home is a seconds-long run; the cold budget
#: covers a home whose database name the implementation resolves elsewhere, so a
#: real dictionary import happens instead.
INSTALL_BUDGET = 120.0
INSTALL_COLD_BUDGET = 300.0

#: An override that must be rejected, not resolved.
RELATIVE_HOME_NAME = "kata-holdout-relative-home"



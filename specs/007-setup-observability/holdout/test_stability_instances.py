def test_two_data_homes_share_no_files_after_two_installs(
    holdout, tmp_path, sandbox_factory, run_installer
):
    """US5/1 + FR-015: installing the second instance neither reads nor writes the first.

    The first home is fingerprinted (every path, size and mtime) before the
    second install and compared afterwards: byte-untouched is the requirement,
    not merely "different paths".
    """
    first_box = sandbox_factory(config=False, seed=False)
    second_box = sandbox_factory(config=False, seed=False)
    first_home, first_seeded = make_home(tmp_path, holdout, "a")
    second_home, second_seeded = make_home(tmp_path, holdout, "b")
    first_box.use_data_home(first_home)
    second_box.use_data_home(second_home)

    first_run = run_installer(first_box, "--yes", timeout=budget(first_seeded))
    assert first_run.returncode == 0, report(first_run, "the first instance's installer")
    assert (first_home / "config.toml").is_file(), report(first_run, "the first instance")

    before = tree_fingerprint(first_home)
    assert before, f"the first instance produced nothing under {first_home}"

    second_run = run_installer(second_box, "--yes", timeout=budget(second_seeded))
    assert second_run.returncode == 0, report(second_run, "the second instance's installer")

    after = tree_fingerprint(first_home)
    added = sorted(set(after) - set(before))
    removed = sorted(set(before) - set(after))
    changed = sorted(key for key in set(before) & set(after) if before[key] != after[key])
    assert not added, f"installing instance B created {added} inside instance A's home"
    assert not removed, f"installing instance B deleted {removed} from instance A's home"
    assert not changed, f"installing instance B modified {changed} inside instance A's home"

    # The second instance is complete in its own home, and the two configs name
    # two different databases -- no shared file behind matching trees.
    second_config = second_home / "config.toml"
    assert second_config.is_file(), report(second_run, "the second instance")
    first_db = config_db_path(first_home / "config.toml")
    second_db = config_db_path(second_config)
    assert inside(second_home, second_db), second_db
    assert not same_path(first_db, second_db), (
        f"both instances point at one database: {second_db}"
    )
    assert not inside(first_home, second_db), (
        f"the second instance's config points into the first instance's home: {second_db}"
    )
    for box in (first_box, second_box):
        assert box.default_home_entries() == [], (
            f"an instance install leaked into the default home: {box.default_home_entries()}"
        )


def test_two_concurrent_servers_each_report_their_own_data_home(
    holdout, tmp_path, sandbox_factory, mcp_server
):
    """US5/2 + FR-016/FR-017: concurrent instances, told apart in one call each.

    Also the failure mode that matters operationally: one instance dying must
    not take the other's session with it.
    """
    first_box = sandbox_factory(config=False, seed=False)
    second_box = sandbox_factory(config=False, seed=False)
    first_home, _ = make_home(tmp_path, holdout, "live-a")
    second_home, _ = make_home(tmp_path, holdout, "live-b")
    first_box.use_data_home(first_home)
    second_box.use_data_home(second_home)

    client_a = mcp_server(first_box)
    client_b = mcp_server(second_box)
    payload_a = client_a.call_tool(TOOL)
    payload_b = client_b.call_tool(TOOL)

    for payload, home, label in ((payload_a, first_home, "A"), (payload_b, second_home, "B")):
        assert "data_home" in payload, f"instance {label} reports no data_home: {sorted(payload)}"
        assert same_path(payload["data_home"], home), (
            f"instance {label} reports data_home {payload['data_home']!r}, not its own {home}"
        )
        assert payload.get("data_home_source") == "env", (
            f"instance {label} resolved its home from KATAGIRI_DATA_HOME, so "
            f"data_home_source must be 'env', got {payload.get('data_home_source')!r}"
        )
        for field in ("config_path", "log_file_path"):
            assert inside(home, payload[field]), (
                f"instance {label} reports {field} outside its data home: {payload[field]}"
            )

    for field in ("data_home", "config_path", "db_path", "log_file_path", "pid"):
        assert payload_a[field] != payload_b[field], (
            f"two side-by-side instances report the same {field}: {payload_a[field]!r}"
        )
    assert not inside(first_home, payload_b["db_path"]), "instance B reports instance A's database"

    # Killing one instance leaves the other answering (SC-002 from a live session).
    client_a.process.kill()
    client_a.process.wait(timeout=15)
    assert client_a.process.poll() is not None, "instance A did not actually die"

    survivor = client_b.call_tool(TOOL)
    assert same_path(survivor["data_home"], second_home), survivor["data_home"]
    assert survivor["pid"] == payload_b["pid"], "the surviving instance was restarted, not survived"


def test_two_checkouts_pointed_at_one_data_home_report_the_same_home(
    holdout, tmp_path, sandbox_factory, mcp_server
):
    """Edge case: sharing one home is allowed, and must be *visible*, not hidden."""
    shared_home, _ = make_home(tmp_path, holdout, "shared")
    first_box = sandbox_factory(config=False, seed=False)
    second_box = sandbox_factory(config=False, seed=False)
    first_box.use_data_home(shared_home)
    second_box.use_data_home(shared_home)

    client_a = mcp_server(first_box)
    client_b = mcp_server(second_box)
    payload_a = client_a.call_tool(TOOL)
    payload_b = client_b.call_tool(TOOL)

    for payload, label in ((payload_a, "A"), (payload_b, "B")):
        assert payload["status"] == "ok", f"instance {label} did not answer cleanly: {payload}"
        assert same_path(payload["data_home"], shared_home), (
            f"instance {label} hides the shared home: {payload['data_home']!r}"
        )
        assert payload.get("data_home_source") == "env", payload.get("data_home_source")

    assert same_path(payload_a["config_path"], payload_b["config_path"]), (
        "two sessions on one data home must report the same config file: "
        f"{payload_a['config_path']!r} vs {payload_b['config_path']!r}"
    )
    assert same_path(payload_a["db_path"], payload_b["db_path"]), (
        f"{payload_a['db_path']!r} vs {payload_b['db_path']!r}"
    )
    assert payload_a["pid"] != payload_b["pid"], (
        "the two sessions must still be distinguishable as processes"
    )



@pytest.mark.parametrize("bad_value", ["", "   "], ids=["empty", "blank"])
def test_an_empty_data_home_override_fails_loudly_and_never_falls_back(
    holdout, sandbox_factory, run_installer, bad_value
):
    """Edge case: an invalid override is an explicit error, never a silent default.

    A silent fallback here is the dangerous failure: the operator believes they
    are working on a disposable instance while writing to the real study
    database (constitution III). So the assertion that matters is the second
    one -- the default home must stay empty.
    """
    box = sandbox_factory(config=False, seed=False)
    box.use_data_home(bad_value)

    proc = run_installer(box, "--yes", timeout=INSTALL_BUDGET)

    assert box.default_home_entries() == [], (
        "an invalid KATAGIRI_DATA_HOME silently fell back to the default home, which is "
        f"exactly what must never happen: {box.default_home_entries()}\n"
        + report(proc, "installer with an invalid data home")
    )
    assert proc.returncode != 0, report(
        proc, "installer with an invalid (empty) KATAGIRI_DATA_HOME"
    )
    told = (proc.stdout or "") + (proc.stderr or "")
    assert "KATAGIRI_DATA_HOME" in told, (
        "the rejection must name the override it is rejecting:\n"
        + report(proc, "installer with an invalid data home")
    )
    holdout.assert_no_traceback(told, where="the invalid-override rejection")


def test_a_relative_data_home_override_is_rejected_and_creates_nothing(
    holdout, sandbox_factory, run_installer_in_mirror, mirror_checkout
):
    """Edge case: a relative override is rejected, not resolved against the cwd.

    Run inside the mirrored checkout so that an implementation which *does*
    resolve it relatively creates its directory somewhere disposable -- and the
    test can still see that it happened.
    """
    box = sandbox_factory(config=False, seed=False)
    box.use_data_home(RELATIVE_HOME_NAME)

    proc = run_installer_in_mirror(box, "--yes", timeout=INSTALL_BUDGET)

    assert box.default_home_entries() == [], (
        "a relative KATAGIRI_DATA_HOME silently fell back to the default home: "
        f"{box.default_home_entries()}\n" + report(proc, "installer with a relative data home")
    )
    resolved = mirror_checkout.root / RELATIVE_HOME_NAME
    assert not resolved.exists(), (
        f"a relative override must be rejected, not resolved against the working directory "
        f"({resolved})\n" + report(proc, "installer with a relative data home")
    )
    assert not (holdout.REPO_ROOT / RELATIVE_HOME_NAME).exists(), (
        "a relative override was resolved against the real checkout"
    )
    assert proc.returncode != 0, report(proc, "installer with a relative data home")
    told = (proc.stdout or "") + (proc.stderr or "")
    assert "KATAGIRI_DATA_HOME" in told, (
        "the rejection must name the override it is rejecting:\n"
        + report(proc, "installer with a relative data home")
    )


def test_a_data_home_that_does_not_exist_yet_is_created_or_clearly_reported(
    holdout, tmp_path, sandbox_factory, run_installer
):
    """Edge case: "points at a not-yet-existing directory -> created, or reported, never a crash".

    Both outcomes are accepted, because the spec accepts both. What is not
    accepted: a crash, or a fallback that puts this instance's data in the
    default home.
    """
    box = sandbox_factory(config=False, seed=False)
    home, _ = make_home(tmp_path, holdout, "absent", create=False)
    assert not home.exists()
    box.use_data_home(home)

    proc = run_installer(box, "--yes", timeout=INSTALL_COLD_BUDGET)

    told = (proc.stdout or "") + (proc.stderr or "")
    holdout.assert_no_traceback(told, where="a run against an absent data home")
    assert box.default_home_entries() == [], (
        "an absent data home must not push this instance's data into the default home: "
        f"{box.default_home_entries()}\n" + report(proc, "installer with an absent data home")
    )

    if proc.returncode == 0:
        assert home.is_dir(), (
            "a successful run must have created the data home it was pointed at:\n"
            + report(proc, "installer with an absent data home")
        )
        assert (home / "config.toml").is_file(), (
            f"the created home holds no config: {[p.name for p in files_under(home)]}"
        )
        assert inside(home, config_db_path(home / "config.toml")), config_db_path(
            home / "config.toml"
        )
    else:
        assert home.name in told or str(home) in told, (
            "a refusal must name the directory it could not use:\n"
            + report(proc, "installer with an absent data home")
        )
        assert not files_under(home), (
            "a refused run left a half-built instance behind: "
            f"{[p.as_posix() for p in files_under(home)]}"
        )

# Precedence (research D9: KATAGIRI_CONFIG > KATAGIRI_DATA_HOME > default)
# ---------------------------------------------------------------------------


def test_katagiri_config_outranks_the_data_home_for_the_config_file_only(
    holdout, tmp_path, sandbox_factory, run_installer, mcp_server
):
    """D9 precedence: the file-specific override wins for the file; logs follow the home."""
    box = sandbox_factory(config=False, seed=False)
    home, seeded = make_home(tmp_path, holdout, "precedence")
    explicit_config = box.root / "explicit-instance-config.toml"
    box.use_data_home(home)
    # Re-assert the higher-precedence override on top of the data home.
    box.env_unset.discard("KATAGIRI_CONFIG")
    box.extra_env["KATAGIRI_CONFIG"] = str(explicit_config)

    proc = run_installer(box, "--yes", timeout=budget(seeded))
    assert proc.returncode == 0, report(proc, "the installer with both overrides set")

    assert explicit_config.is_file(), (
        f"KATAGIRI_CONFIG must still decide the config file's path ({explicit_config}); "
        f"the data home holds: {[p.name for p in files_under(home)]}"
    )
    assert not (home / "config.toml").exists(), (
        "the data home must not get a second config file when KATAGIRI_CONFIG names one"
    )
    assert log_files_under(home), (
        "logs follow the data home even when KATAGIRI_CONFIG points elsewhere; "
        f"the home holds: {[p.as_posix() for p in files_under(home)]}"
    )
    assert box.default_home_entries() == [], (
        f"the default home was written to anyway: {box.default_home_entries()}"
    )

    # The same precedence, as the diagnostic reports it.
    payload = mcp_server(box).call_tool(TOOL)
    assert same_path(payload["config_path"], explicit_config), payload["config_path"]
    assert same_path(payload["data_home"], home), payload["data_home"]
    assert inside(home, payload["log_file_path"]), payload["log_file_path"]



def test_a_data_home_override_puts_config_database_and_logs_under_it(
    holdout, tmp_path, sandbox_factory, run_installer
):
    """US5/2 + FR-014: the whole instance lives inside the override, and only there."""
    box = sandbox_factory(config=False, seed=False)
    home, seeded = make_home(tmp_path, holdout, "solo")
    box.use_data_home(home)

    proc = run_installer(box, "--yes", timeout=budget(seeded))
    assert proc.returncode == 0, report(proc, "the installer under a data home")

    config_file = home / "config.toml"
    assert config_file.is_file(), (
        f"no config.toml under the data home {home}; the installer wrote: "
        f"{[p.name for p in files_under(home)]}\n" + report(proc, "installer")
    )
    db_path = config_db_path(config_file)
    assert inside(home, db_path), f"the config under the data home points its database at {db_path}"
    assert Path(db_path).is_file(), f"the instance database was never created at {db_path}"
    assert log_files_under(home), (
        f"the instance wrote no log file under its own data home {home}: "
        f"{[p.as_posix() for p in files_under(home)]}"
    )

    # ...and nothing at all reached the default home (no silent split-brain).
    assert box.default_home_entries() == [], (
        "a run with KATAGIRI_DATA_HOME set still wrote to the default home: "
        f"{box.default_home_entries()}"
    )


def test_no_override_keeps_the_default_local_app_data_home(
    holdout, sandbox_factory, run_installer
):
    """US5/3 + FR-014 regression: with no override, today's behavior, unchanged.

    This is the one test in this module that must pass *before* the feature is
    implemented: it pins the pre-007 resolution so the instance work cannot
    move the existing install's data as a side effect. Deliberately narrow --
    the install chain itself is covered by test_stability_install.py.
    """
    box = sandbox_factory(config=False)
    box.use_default_home()
    assert "KATAGIRI_DATA_HOME" not in box.env(), "this test must run with no override at all"
    assert "KATAGIRI_CONFIG" not in box.env(), "this test must run with no override at all"

    proc = run_installer(box, "--yes")
    assert proc.returncode == 0, report(proc, "the installer with no override")

    expected = box.katagiri_dir / "config.toml"
    assert expected.is_file(), (
        f"with no override the config must land in %LOCALAPPDATA%\\Katagiri ({expected}); "
        f"found instead: {box.default_home_entries()}"
    )
    assert inside(box.katagiri_dir, config_db_path(expected)), (
        "with no override the database must stay under %LOCALAPPDATA%\\Katagiri: "
        + config_db_path(expected)
    )
    assert log_files_under(box.katagiri_dir), (
        "with no override the logs must stay under %LOCALAPPDATA%\\Katagiri\\logs; "
        f"found: {[p.as_posix() for p in files_under(box.katagiri_dir)]}"
    )


